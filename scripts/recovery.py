"""Изолированная лабораторная backup/restore, streaming replication и остановок."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
import re
import subprocess
import sys
import time
import uuid

from scripts.db import ROOT
from security.init_env import read_env


def require(condition, message):
    # These checks must also work under python -O.
    if not condition:
        raise RuntimeError(message)


def normalized_schema(schema):
    # PG18 reparses varchar[]::text[] into per-element casts on restore.
    # Normalize only literal arrays on CHECK lines, preserving every value/cast.
    literal = r"'(?:[^']|'')*'::character varying"
    array_cast = r'\(ARRAY\[(' + literal + r'(?:, ' + literal + r')*)\]\)::text\[\]'
    lines = []
    for line in schema.splitlines():
        if line.startswith(('\\restrict ', '\\unrestrict ')):
            continue  # Random psql guard token generated by pg_dump 18.
        if re.match(r'\s+CONSTRAINT \S+ CHECK ', line):
            line = re.sub(array_cast, lambda match: 'ARRAY[' + ', '.join(
                f'({value})::text' for value in re.findall(literal, match[1])) + ']', line)
        lines.append(line)
    return '\n'.join(lines)


class Lab:
    def __init__(self, project):
        require(re.fullmatch(r'bd-news-recovery(?:-[a-z0-9-]+)?', project),
                'Имя проекта должно начинаться с bd-news-recovery')
        self.project = project
        self.env = os.environ | {
            'COMPOSE_PROJECT_NAME': project,
            'COMPOSE_FILE': f'{ROOT / "compose.yaml"}:{ROOT / "recovery/compose.yaml"}',
            'COMPOSE_PROFILES': 'recovery', 'POSTGRES_PORT': '0',
        }
        self.directory = ROOT / 'artifacts/recovery' / project
        self.directory.mkdir(parents=True, exist_ok=True)
        self.backups = ROOT / '.secrets/recovery' / project
        self.backups.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.backups.chmod(0o700)
        self.dump = self.backups / 'news.dump'

    def safe(self, text):
        values = read_env(ROOT / '.env') | self.env
        for key, value in values.items():
            if 'PASSWORD' in key and value:
                text = text.replace(value, '[REDACTED]')
        return text

    def event(self, message):
        line = f'{datetime.now(timezone.utc).isoformat(timespec="seconds")} {self.safe(message)}'
        with (self.directory / 'events.txt').open('a') as stream:
            stream.write(line + '\n')
        print(line, flush=True)

    def run(self, args, *, input=None, output=None, check=True, timeout=180):
        result = subprocess.run(args, cwd=ROOT, env=self.env, input=input,
                                stdout=output or subprocess.PIPE, stderr=subprocess.PIPE,
                                timeout=timeout)
        if check and result.returncode:
            raise RuntimeError(f'Команда {args[0]}: exit={result.returncode}\n'
                               + self.safe(result.stderr.decode(errors='replace')))
        return result

    def compose(self, *args, **kwargs):
        return self.run(['docker', 'compose', *args], **kwargs)

    def sql(self, sql='', *, service='postgres', role='bootstrap', file=None, check=True):
        if role == 'bootstrap':
            login = 'exec psql -U news_bootstrap -d "$POSTGRES_DB" "$@"'
        else:
            require(role == 'admin', 'Недопустимая роль обслуживания')
            login = ('PGPASSWORD="$ADMIN_PASSWORD" exec psql -h 127.0.0.1 '
                     '-U news_admin -d "$POSTGRES_DB" "$@"')
        args = ['exec', '-T', service, 'sh', '-c', login, 'sh',
                '-X', '-w', '-qAt', '-v', 'ON_ERROR_STOP=1', '-P', 'pager=off']
        if file:
            args += ['-f', f'/workspace/{file}']
        return self.compose(*args, input=sql.encode(), check=check).stdout.decode().strip()

    def scalar(self, sql, service='postgres'):
        return self.sql(sql, service=service)

    def wait(self, predicate, description):
        deadline = time.monotonic() + 90
        while time.monotonic() < deadline:
            if predicate():
                self.event('PASS: ' + description)
                return
            time.sleep(1)
        raise RuntimeError('Истёк срок ожидания: ' + description)

    def streaming(self):
        return self.scalar("SELECT count(*) = 1 FROM pg_stat_replication "
                           "WHERE application_name = 'news_replica' AND state = 'streaming';") == 't'

    def up(self):
        self.run(['sh', 'start.sh'])
        if self.scalar('SELECT count(*) FROM public.news;') == '0':
            self.sql(role='admin', file='run_seed_only.sql')
        self.sql(role='admin', file='recovery/fixture.sql')
        self.sql(file='recovery/roles.sql')
        self.compose('up', '-d', '--wait', 'replica')
        require(self.scalar('SELECT pg_is_in_recovery();') == 'f', 'Primary в recovery')
        require(self.scalar('SELECT pg_is_in_recovery();', 'replica') == 't', 'Replica вне recovery')
        self.wait(self.streaming, 'replica в recovery, primary видит streaming')
        require(self.scalar("SELECT rolreplication AND NOT rolsuper AND NOT rolcreatedb "
                            "AND NOT rolcreaterole AND NOT rolbypassrls FROM pg_roles "
                            "WHERE rolname='news_replicator';") == 't', 'Неверные права репликатора')
        self.compose('exec', '-T', 'replica', 'sh', '-c',
                     'test "$(stat -c %a /var/lib/postgresql/replication.pgpass)" = 600 '
                     '&& ! grep -q "password=" "$PGDATA/postgresql.auto.conf"')
        self.event('PASS: отдельный стенд готов: ' + self.project)

    def snapshot(self, service='postgres'):
        data = self.sql(file='recovery/fingerprint.sql', service=service)
        result = self.compose('exec', '-T', service, 'sh', '-c',
                              'exec pg_dump -U news_bootstrap -d "$POSTGRES_DB" --schema-only')
        schema = normalized_schema(result.stdout.decode())
        schema_path = self.backups / f'{service}.schema.sql'
        descriptor = os.open(schema_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(descriptor, 'w') as stream:
            stream.write(schema)
        return {'data_and_sequences': data.splitlines(),
                'schema_sha256': hashlib.sha256(schema.encode()).hexdigest()}

    def backup(self):
        before = self.snapshot()
        temporary = self.dump.with_suffix('.tmp')
        try:
            descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            os.fchmod(descriptor, 0o600)
            with os.fdopen(descriptor, 'wb') as stream:
                self.compose('exec', '-T', 'postgres', 'sh', '-c',
                             'exec pg_dump -U news_bootstrap -d "$POSTGRES_DB" --format=custom',
                             output=stream)
            require(before == self.snapshot(), 'Данные менялись во время backup; повторите без записей')
            temporary.replace(self.dump)
        finally:
            temporary.unlink(missing_ok=True)
        manifest = before | {'dump_sha256': hashlib.sha256(self.dump.read_bytes()).hexdigest(),
                             'dump_bytes': self.dump.stat().st_size}
        (self.directory / 'backup.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
        self.event(f'PASS: pg_dump custom, {manifest["dump_bytes"]} байт, файл 0600; backup.json')

    def empty_restore(self):
        self.compose('up', '-d', '--wait', 'restore')
        require(self.scalar("SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
                            "WHERE n.nspname NOT LIKE 'pg_%' AND n.nspname <> 'information_schema' "
                            "AND c.relkind IN ('r','p');", 'restore') == '0',
                'Restore разрешён только в экземпляр без пользовательских таблиц')

    def restore(self):
        require(self.dump.is_file(), 'Сначала выполните backup')
        manifest = json.loads((self.directory / 'backup.json').read_text())
        require(hashlib.sha256(self.dump.read_bytes()).hexdigest() == manifest['dump_sha256'],
                'Контрольная сумма дампа не совпадает')
        self.empty_restore()
        self.event('PASS: новый restore не содержит пользовательских таблиц')
        # A read-only bind mount exposes only the existing local project backup.
        path = '/workspace/' + str(self.dump.relative_to(ROOT))
        self.compose('exec', '-T', 'restore', 'sh', '-c',
                     'exec pg_restore -U news_bootstrap -d "$POSTGRES_DB" '
                     '--single-transaction --exit-on-error "$1"', 'sh', path)
        actual = self.snapshot('restore')
        (self.directory / 'restore.json').write_text(json.dumps(actual, ensure_ascii=False, indent=2) + '\n')
        require(all(actual[key] == manifest[key] for key in actual),
                'Данные, sequences или структура восстановленной БД отличаются от backup')
        self.sql(file='recovery/integrity.sql', service='restore')
        self.event('PASS: restore; данные, sequences, структура/ACL/владельцы совпали; FK/индексы/миграции OK')

    def probe(self, label, *, fails=False):
        # --no-deps is essential: outage checks must not restart the primary.
        result = self.compose('run', '--rm', '-T', '--no-deps', '-e', 'PGCONNECT_TIMEOUT=3',
                              'app', '-qAt', '-v', f'label={label}',
                              '-f', '/workspace/recovery/probe.sql', check=False, timeout=45)
        if fails:
            stderr = result.stderr.decode(errors='replace')
            require(result.returncode == 2 and any(message in stderr for message in
                    ('Connection refused', 'could not translate host name',
                     'timeout expired', 'No route to host')),
                    f'Ожидался сетевой отказ psql (exit=2), получен exit={result.returncode}: {self.safe(stderr)}')
            self.event(f'PASS: news_app/{label}: ожидаемый сетевой отказ, exit=2\n' + stderr.strip())
        else:
            require(result.returncode == 0,
                    f'news_app exit={result.returncode}: {self.safe(result.stderr.decode(errors="replace"))}')
            require(f'{label}|news_app' in result.stdout.decode(), 'Нет подтверждения COMMIT приложения')
            self.event(f'PASS: news_app/{label}: чтение news и COMMIT маркера, exit=0')

    def replicated(self, label):
        require(re.fullmatch(r'[a-z0-9_-]+', label), 'Недопустимый маркер')
        self.wait(lambda: self.scalar(f"SELECT EXISTS(SELECT FROM recovery_lab.probe WHERE label='{label}');",
                                       'replica') == 't', f'маркер {label} получен на replica')

    def outages(self):
        suffix = uuid.uuid4().hex[:8]
        before_stop, replica_down, primary_down, primary_back = (
            f'{stage}_{suffix}' for stage in ('before_stop', 'replica_down', 'primary_down', 'primary_back'))
        self.probe(before_stop)
        self.replicated(before_stop)
        before = self.snapshot()
        self.event('Действие: docker compose stop replica')
        self.compose('stop', 'replica')
        self.wait(lambda: self.scalar('SELECT count(*) FROM pg_stat_replication;') == '0',
                  'primary видит отсутствие replica')
        self.probe(replica_down)
        self.event('Восстановление: docker compose start --wait replica')
        self.compose('start', '--wait', 'replica')
        self.wait(self.streaming, 'streaming после запуска replica')
        self.replicated(replica_down)
        expected = self.snapshot()
        self.event('Действие: docker compose stop postgres (primary)')
        self.compose('stop', 'postgres')
        self.probe(primary_down, fails=True)
        running = self.compose('ps', '--status', 'running', '--services').stdout.decode().splitlines()
        require('postgres' not in running, 'Проба незаметно запустила primary')
        require(self.scalar('SELECT pg_is_in_recovery();', 'replica') == 't', 'Replica повышена до primary')
        self.event('PASS: replica остаётся standby; клиент не перезапустил primary')
        self.event('Восстановление: docker compose start --wait postgres')
        self.compose('start', '--wait', 'postgres')
        require(self.snapshot() == expected, 'Данные primary изменились после stop/start')
        require(self.scalar(f"SELECT count(*) FROM recovery_lab.probe WHERE label='{primary_down}';") == '0',
                'Неуспешная проба сохранила данные')
        self.probe(primary_back)
        self.wait(self.streaming, 'streaming после запуска primary')
        self.replicated(primary_back)
        self.sql(file='recovery/integrity.sql')
        self.sql(file='recovery/integrity.sql', service='replica')
        # Sequence caches can differ on physical replicas; compare committed table rows.
        primary_rows = [x for x in self.snapshot()['data_and_sequences'] if not x.endswith(('|t', '|f'))]
        replica_rows = [x for x in self.snapshot('replica')['data_and_sequences'] if not x.endswith(('|t', '|f'))]
        require(primary_rows == replica_rows, 'Таблицы replica отличаются после восстановления')
        require(before['schema_sha256'] == expected['schema_sha256'], 'Эксперимент изменил схему')
        self.event('PASS: оба эксперимента завершены; все таблицы primary/replica совпали')
        return primary_back

    def down(self):
        self.compose('down', '--volumes', '--remove-orphans')
        self.event('Удалены только контейнеры/тома проекта ' + self.project)


def verify(lab):
    try:
        lab.up()
        lab.event('PostgreSQL ' + lab.scalar('SHOW server_version;'))
        lab.backup()
        lab.empty_restore()
        # Reject a malformed archive before any objects can be restored.
        bad = lab.compose('exec', '-T', 'restore', 'sh', '-c',
                          'exec pg_restore -U news_bootstrap -d "$POSTGRES_DB" '
                          '--single-transaction --exit-on-error', input=b'not a PostgreSQL archive', check=False)
        require(bad.returncode != 0 and b'input file' in bad.stderr, 'Повреждённый архив не отклонён pg_restore')
        lab.empty_restore()
        lab.event('PASS: повреждённый архив отклонён, restore остаётся пустым')
        archive = '/workspace/' + str(lab.dump.relative_to(ROOT))
        toc = lab.compose('exec', '-T', 'restore', 'pg_restore', '--list', archive).stdout
        # Exclude a required table: restore starts DDL, then fails on its sequence/FK.
        broken_toc = b'\n'.join(line for line in toc.splitlines()
                                 if b' TABLE public role news_admin' not in line) + b'\n'
        require(broken_toc != toc, 'TOC не содержит ожидаемую таблицу role')
        failed = lab.compose('exec', '-T', 'restore', 'sh', '-c',
                             'PGOPTIONS="-c log_error_verbosity=verbose" '
                             'exec pg_restore -U news_bootstrap -d "$POSTGRES_DB" '
                             '--single-transaction --exit-on-error --use-list=/dev/stdin "$1"',
                             'sh', archive, input=broken_toc, check=False)
        require(failed.returncode != 0 and b'public.role' in failed.stderr
                and b'does not exist' in failed.stderr, 'Не получена ожидаемая SQL-ошибка restore')
        # pg_restore omits SQLSTATE on stderr; the server emits it in verbose logs.
        diagnostic = lab.compose('logs', '--no-color', '--tail=30', 'restore').stdout
        require(b'42P01: relation "public.role" does not exist' in diagnostic,
                'Не подтверждён ожидаемый SQLSTATE 42P01')
        lab.empty_restore()
        lab.event('PASS: SQLSTATE 42P01 внутри pg_restore откатил созданные объекты транзакции')
        lab.restore()
        try:
            lab.restore()
        except RuntimeError as error:
            require('без пользовательских таблиц' in str(error), 'Неверная причина отказа повторного restore')
        else:
            raise RuntimeError('Restore в непустую БД неожиданно разрешён')
        lab.event('PASS: повторный restore в непустую БД запрещён')
        last_label = lab.outages()
        lab.up()
        lab.replicated(last_label)
        lab.event('PASS: повторный up сохранил данные и рабочую replica')
    except BaseException as error:
        lab.event('FAIL: ' + str(error))
        diagnostic = lab.compose('logs', '--no-color', '--tail=25', check=False)
        lab.event('Диагностика:\n' + diagnostic.stdout.decode(errors='replace'))
        raise
    finally:
        lab.down()
    lab.event('PASS: полная проверка лабораторной 4')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', default='bd-news-recovery', help='Только bd-news-recovery[-суффикс]')
    parser.add_argument('action', choices=['up', 'backup', 'restore', 'outages', 'verify', 'down', 'compose'])
    parser.add_argument('arguments', nargs=argparse.REMAINDER, help='Аргументы для compose')
    args = parser.parse_args()
    project = f'bd-news-recovery-check-{uuid.uuid4().hex[:8]}' if args.action == 'verify' else args.project
    lab = Lab(project)
    try:
        if args.action == 'verify':
            verify(lab)
            print('Журнал: ' + str(lab.directory / 'events.txt'))
        elif args.action == 'compose':
            result = lab.compose(*args.arguments)
            print(lab.safe(result.stdout.decode()), end='')
        else:
            require(not args.arguments, 'Лишние аргументы')
            getattr(lab, args.action)()
    except (RuntimeError, subprocess.TimeoutExpired, OSError) as error:
        print(lab.safe(str(error)), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
